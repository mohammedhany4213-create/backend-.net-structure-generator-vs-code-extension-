    await createProject('classlib', business, options.targetFramework, src);
    await createProject('classlib', data, options.targetFramework, src);
    await createProject('classlib', models, options.targetFramework, src);
    await addProjectsToSolution(projectRoot, solutionFile, [
        path.join('src', entry, `${entry}.csproj`),
        path.join('src', business, `${business}.csproj`),
        path.join('src', data, `${data}.csproj`),
        path.join('src', models, `${models}.csproj`),
    ]);
    await runDotnet(['add', path.join('src', business, `${business}.csproj`), 'reference', path.join('src', models, `${models}.csproj`)], projectRoot);
    await runDotnet(['add', path.join('src', data, `${data}.csproj`), 'reference', path.join('src', business, `${business}.csproj`), path.join('src', models, `${models}.csproj`)], projectRoot);
    await runDotnet(['add', path.join('src', entry, `${entry}.csproj`), 'reference', path.join('src', business, `${business}.csproj`), path.join('src', data, `${data}.csproj`), path.join('src', models, `${models}.csproj`)], projectRoot);

